/**
 * Regenerates the configuration reference in PlatformDocumentation.md (§12.3)
 * from the code: env-only keys below plus every runtime setting in the
 * registry. `settingsDocs.test.ts` fails when the docs are out of date.
 *
 * Run: npm run docs:settings
 */
import fs from "fs";
import path from "path";
import { SETTINGS_REGISTRY } from "../config/settings.registry";

/** Environment-only keys (never stored in the DB). Keep in step with config/env.ts and lib/configLoader.ts. */
export const ENV_DOCS: [key: string, required: string, description: string][] = [
  ["NODE_ENV", "Yes", "`development`, `test` or `production`"],
  ["PORT", "No", "HTTP port (default 4000)"],
  ["MONGODB_URI", "Yes", "MongoDB connection string"],
  ["FRONTEND_URL", "Yes", "Public site URL: CORS origin and base for links in emails"],
  ["CORS_ORIGINS", "No", "Extra allowed browser origins, comma-separated"],
  ["TRUST_PROXY", "Production", "Number of proxies in front of the API (for client IPs and rate limits)"],
  ["JWT_SECRET", "Yes", "≥ 32 random chars — `openssl rand -base64 48`"],
  ["JWT_REFRESH_SECRET", "Yes", "≥ 32 random chars, different from `JWT_SECRET`"],
  ["JWT_EXPIRY", "No", "Access-token lifetime (default `15m`)"],
  ["STRIPE_SECRET_KEY", "Production", "`sk_live_…` / `sk_test_…`"],
  ["STRIPE_WEBHOOK_SECRET", "Production", "`whsec_…` for the webhook endpoint"],
  ["RESEND_API_KEY", "Production", "`re_…`; without it emails fail as `EMAIL_NOT_CONFIGURED`"],
  ["GROQ_API_KEY", "For AI", "Groq API key"],
  ["CLOUDINARY_CLOUD_NAME", "Production", "Cloudinary cloud"],
  ["CLOUDINARY_API_KEY", "Production", "Cloudinary API key"],
  ["CLOUDINARY_API_SECRET", "Production", "Cloudinary API secret"],
  ["LOG_LEVEL", "No", "`fatal`…`debug`/`silent`"],
  ["SENTRY_DSN", "No", "Error tracking"],
  ["METRICS_TOKEN", "No", "Enables `GET /metrics`"],
  ["GIT_SHA", "No", "Build revision (set by the Docker build)"],
  ["ADMIN_SEED_EMAIL / _PASSWORD / _NAME", "Seeding only", "First admin for `npm run seed:admin` (password ≥ 12 chars)"],
];

const START = "<!-- settings:start (generated by `npm run docs:settings` — do not edit by hand) -->";
const END = "<!-- settings:end -->";
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderSettingsDoc(): string {
  const env = ENV_DOCS.map(([k, r, d]) => `| \`${k}\` | ${r} | ${cell(d)} |`).join("\n");
  const runtime = SETTINGS_REGISTRY.map(
    (s) => `| \`${s.key}\` | ${s.section} | ${cell(s.label)}${s.description ? ` — ${cell(s.description)}` : ""} | ${s.default === "" ? "—" : `\`${cell(s.default)}\``} |`
  ).join("\n");
  return [
    START,
    "**Environment only** (host secret store / `.env`; never read from the database):",
    "",
    "| Variable | Required | Notes |",
    "|---|---|---|",
    env,
    "",
    "**Runtime settings** (Admin → Settings; stored in MongoDB, fall back to an env var of the same name, then the default):",
    "",
    "| Key | Section | Meaning | Default |",
    "|---|---|---|---|",
    runtime,
    END,
  ].join("\n");
}

export const DOC_PATH = path.resolve(__dirname, "../../../PlatformDocumentation.md");

export function currentSettingsBlock(doc: string): string | null {
  const a = doc.indexOf(START.slice(0, 20));
  const b = doc.indexOf(END);
  return a === -1 || b === -1 ? null : doc.slice(a, b + END.length);
}

if (require.main === module) {
  const doc = fs.readFileSync(DOC_PATH, "utf8");
  const block = currentSettingsBlock(doc);
  if (!block) throw new Error("Settings markers not found in PlatformDocumentation.md");
  fs.writeFileSync(DOC_PATH, doc.replace(block, renderSettingsDoc()));
  console.log("✅ PlatformDocumentation.md settings reference updated");
}
